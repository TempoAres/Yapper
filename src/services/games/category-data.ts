export function normalizeCategoryAnswer(answer: string): string {
  return answer.trim().toLowerCase().normalize("NFKD")
    .replace(/\p{M}/gu, "")
    .replace(/[’‘]/g, "'")
    .replace(/[_\s-]+/g, " ");
}

export function categoryAnswerKey(category: string, answer: string): string {
  const normalized = normalizeCategoryAnswer(answer);
  return aliases[category]?.[normalized] ?? normalized;
}
